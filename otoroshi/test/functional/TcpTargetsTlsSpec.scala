package functional

import com.typesafe.config.ConfigFactory
import otoroshi.env.Env
import otoroshi.ssl.{Cert, ClientAuth, DynamicSSLEngineProvider}
import otoroshi.ssl.pki.models.GenCsrQuery
import otoroshi.tcp.*
import otoroshi.utils.syntax.implicits.*
import play.api.Configuration

import java.io.{BufferedReader, InputStreamReader, PrintWriter}
import java.net.{InetSocketAddress, ServerSocket, Socket}
import java.security.cert.X509Certificate
import java.security.{KeyStore, SecureRandom}
import java.util.concurrent.ConcurrentLinkedQueue
import java.util.concurrent.atomic.AtomicBoolean
import javax.net.ssl.*
import scala.concurrent.duration.*
import scala.util.Try

// the tls of a tcp service: it terminates the tls of its clients when asked to, and calls its targets over tls when
// they ask for it (otoroshi is then the tls client of the target), except in passthrough where the tls of the client
// goes through as is
class TcpTargetsTlsSpec extends OtoroshiSpec {

  override def getTestConfiguration(configuration: Configuration): Configuration =
    Configuration(
      ConfigFactory
        .parseString(s"""
          |otoroshi.next.state-sync-interval = 5
          |""".stripMargin)
        .resolve()
    ).withFallback(configuration)

  // an echo server, over tls when it has a context: it answers each line it reads with the same line, and keeps the
  // errors of its connections
  private class EchoServer(context: Option[SSLContext]) {
    private val server  = context.map(_.getServerSocketFactory.createServerSocket(0)).getOrElse(new ServerSocket(0))
    private val running = new AtomicBoolean(true)
    val port: Int       = server.getLocalPort
    val errors          = new ConcurrentLinkedQueue[String]()
    private val thread  = new Thread(() => {
      while (running.get()) {
        Try {
          val socket = server.accept()
          new Thread(() => {
            Try {
              val in  = new BufferedReader(new InputStreamReader(socket.getInputStream))
              val out = new PrintWriter(socket.getOutputStream, true)
              Option(in.readLine()).foreach(line => out.println(line))
              socket.close()
            }.failed.foreach(e => errors.add(String.valueOf(e.getMessage)))
            ()
          }).start()
        }
      }
    })
    thread.setDaemon(true)
    thread.start()
    def stop(): Unit = {
      running.set(false)
      Try(server.close())
    }
  }

  // a certificate for localhost signed by the intermediate ca of otoroshi, which otoroshi trusts as a tls client, or a
  // self signed one that otoroshi does not know. the ca is generated by a job a few seconds after the start
  private def echoServerContext(signedByOtoroshi: Boolean = true)(using env: Env): SSLContext = {
    val query    = GenCsrQuery(hosts = Seq("localhost"), subject = Some("CN=localhost"))
    val (resp, chain) = if (signedByOtoroshi) {
      val deadline = System.currentTimeMillis() + 60000L
      while (
        !DynamicSSLEngineProvider.certificates.contains(Cert.OtoroshiIntermediateCA) &&
        System.currentTimeMillis() < deadline
      ) Thread.sleep(500)
      val ca   = DynamicSSLEngineProvider.certificates(Cert.OtoroshiIntermediateCA).enrich()
      val resp = env.pki
        .genCert(query, ca.certificate.get, ca.certificates.tail, ca.cryptoKeyPair.getPrivate)
        .futureValue
        .toOption
        .get
      (resp, Seq(resp.cert, resp.ca) ++ resp.caChain)
    } else {
      val resp = env.pki.genSelfSignedCert(query).futureValue.toOption.get
      (resp, Seq(resp.cert))
    }
    val keyStore = KeyStore.getInstance("JKS")
    keyStore.load(null, null)
    keyStore.setKeyEntry("server", resp.key, Array.emptyCharArray, chain.toArray[java.security.cert.Certificate])
    val kmf      = KeyManagerFactory.getInstance("SunX509")
    kmf.init(keyStore, Array.emptyCharArray)
    val ctx      = SSLContext.getInstance("TLS")
    ctx.init(kmf.getKeyManagers, null, new SecureRandom())
    ctx
  }

  private def awaitListening(port: Int): Unit = {
    val deadline = System.currentTimeMillis() + 30000L
    while (
      !Try { val s = new Socket(); s.connect(new InetSocketAddress("127.0.0.1", port), 500); s.close() }.isSuccess &&
      System.currentTimeMillis() < deadline
    ) Thread.sleep(200)
  }

  private def echoOnce(socket: Socket, line: String): Option[String] = Try {
    socket.setSoTimeout(5000)
    val out = new PrintWriter(socket.getOutputStream, true)
    out.println(line)
    val in  = new BufferedReader(new InputStreamReader(socket.getInputStream))
    val res = in.readLine()
    socket.close()
    res
  }.toOption.flatMap(Option(_))

  // the tls contexts of otoroshi are rebuilt asynchronously once the ca is loaded, the first calls may come before
  private def echo(socket: () => Socket, line: String): Option[String] = {
    val deadline = System.currentTimeMillis() + 20000L
    var result   = echoOnce(socket(), line)
    while (result.isEmpty && System.currentTimeMillis() < deadline) {
      Thread.sleep(1000)
      result = echoOnce(socket(), line)
    }
    result
  }

  private val trustAll: SSLContext = {
    val ctx = SSLContext.getInstance("TLS")
    ctx.init(
      null,
      Array[TrustManager](new X509TrustManager {
        override def checkClientTrusted(chain: Array[X509Certificate], authType: String): Unit = ()
        override def checkServerTrusted(chain: Array[X509Certificate], authType: String): Unit = ()
        override def getAcceptedIssuers: Array[X509Certificate]                              = Array.empty
      }),
      new SecureRandom()
    )
    ctx
  }

  // a tls client that trusts any server, sending the given sni
  private def tlsClient(port: Int, sni: Option[String] = None): Socket = {
    val socket = trustAll.getSocketFactory.createSocket("127.0.0.1", port).asInstanceOf[SSLSocket]
    sni.foreach { name =>
      val params = socket.getSSLParameters
      params.setServerNames(java.util.List.of(new SNIHostName(name)))
      socket.setSSLParameters(params)
    }
    socket
  }

  "A tcp service" should {
    "warm up" in {
      startOtoroshi()
    }
    "terminate the tls of its clients" in {
      given env: Env = otoroshiComponents.env
      val echoServer = new EchoServer(None)
      val port       = TargetService.freePort
      val service    = TcpService(
        enabled = true,
        tls = TlsMode.Enabled,
        sni = SniSettings(enabled = false, forwardIfNoMatch = false),
        clientAuth = ClientAuth.None,
        port = port,
        rules = Seq(TcpRule("*", Seq(TcpTarget("localhost", Some("127.0.0.1"), echoServer.port, tls = false)))),
        tags = Seq.empty,
        metadata = Map.empty
      )
      env.datastores.tcpServiceDataStore.set(service).futureValue
      try {
        awaitListening(port)
        // the certificate is picked from the sni, here the wildcard certificate of otoroshi
        echo(() => tlsClient(port, Some("tcp.oto.tools")), "hello from a tls client") mustBe Some(
          "hello from a tls client"
        )
      } finally {
        env.datastores.tcpServiceDataStore.delete(service.id).futureValue
        echoServer.stop()
      }
    }
    "call its targets over tls when they ask for it" in {
      given env: Env = otoroshiComponents.env
      val echoServer = new EchoServer(Some(echoServerContext()))
      val port       = TargetService.freePort
      val service    = TcpService(
        enabled = true,
        tls = TlsMode.Disabled,
        sni = SniSettings(enabled = false, forwardIfNoMatch = false),
        clientAuth = ClientAuth.None,
        port = port,
        rules = Seq(TcpRule("*", Seq(TcpTarget("localhost", Some("127.0.0.1"), echoServer.port, tls = true)))),
        tags = Seq.empty,
        metadata = Map.empty
      )
      env.datastores.tcpServiceDataStore.set(service).futureValue
      try {
        awaitListening(port)
        echo(() => new Socket("127.0.0.1", port), "hello over tls") mustBe Some("hello over tls")
      } finally {
        env.datastores.tcpServiceDataStore.delete(service.id).futureValue
        echoServer.stop()
      }
    }
    "not call its targets over tls when their certificate is not trusted or not issued for their host" in {
      given env: Env = otoroshiComponents.env
      val untrusted  = new EchoServer(Some(echoServerContext(signedByOtoroshi = false)))
      val trusted    = new EchoServer(Some(echoServerContext()))
      val port       = TargetService.freePort
      // the certificate of the trusted server is issued for localhost
      val service    = TcpService(
        enabled = true,
        tls = TlsMode.Disabled,
        sni = SniSettings(enabled = false, forwardIfNoMatch = false),
        clientAuth = ClientAuth.None,
        port = port,
        rules = Seq(TcpRule("*", Seq(TcpTarget("localhost", Some("127.0.0.1"), untrusted.port, tls = true)))),
        tags = Seq.empty,
        metadata = Map.empty
      )
      val otherHost  = service.copy(
        id = s"${service.id}-other-host",
        port = TargetService.freePort,
        rules = Seq(TcpRule("*", Seq(TcpTarget("other.oto.tools", Some("127.0.0.1"), trusted.port, tls = true))))
      )
      val sameHost   = service.copy(
        id = s"${service.id}-same-host",
        port = TargetService.freePort,
        rules = Seq(TcpRule("*", Seq(TcpTarget("localhost", Some("127.0.0.1"), trusted.port, tls = true))))
      )
      Seq(service, otherHost, sameHost).foreach(s => env.datastores.tcpServiceDataStore.set(s).futureValue)
      try {
        Seq(service, otherHost, sameHost).foreach(s => awaitListening(s.port))
        // once the target with a trusted certificate answers, the tls contexts of otoroshi are up to date
        echo(() => new Socket("127.0.0.1", sameHost.port), "hello") mustBe Some("hello")
        echoOnce(new Socket("127.0.0.1", service.port), "hello") mustBe None
        echoOnce(new Socket("127.0.0.1", otherHost.port), "hello") mustBe None
        // otoroshi, as the tls client, ends both handshakes because of the certificate
        untrusted.errors.toArray.toSeq.map(_.toString) must contain("Received fatal alert: certificate_unknown")
        trusted.errors.toArray.toSeq.map(_.toString) must contain("Received fatal alert: certificate_unknown")
      } finally {
        Seq(service, otherHost, sameHost).foreach(s => env.datastores.tcpServiceDataStore.delete(s.id).futureValue)
        untrusted.stop()
        trusted.stop()
      }
    }
    "let the tls of its clients go through in passthrough, whatever the tls of its targets" in {
      given env: Env = otoroshiComponents.env
      val ruleServer     = new EchoServer(Some(echoServerContext()))
      val fallbackServer = new EchoServer(Some(echoServerContext()))
      val port           = TargetService.freePort
      val service        = TcpService(
        enabled = true,
        tls = TlsMode.PassThrough,
        sni = SniSettings(
          enabled = true,
          forwardIfNoMatch = true,
          forwardsTo = TcpTarget("localhost", Some("127.0.0.1"), fallbackServer.port, tls = true)
        ),
        clientAuth = ClientAuth.None,
        port = port,
        rules = Seq(TcpRule("rule.oto.tools", Seq(TcpTarget("localhost", Some("127.0.0.1"), ruleServer.port, tls = true)))),
        tags = Seq.empty,
        metadata = Map.empty
      )
      env.datastores.tcpServiceDataStore.set(service).futureValue
      try {
        awaitListening(port)
        // the clients do the tls handshake with the targets themselves
        echo(() => tlsClient(port, Some("rule.oto.tools")), "hello through the rule") mustBe Some(
          "hello through the rule"
        )
        echo(() => tlsClient(port, Some("fallback.oto.tools")), "hello through the fallback") mustBe Some(
          "hello through the fallback"
        )
      } finally {
        env.datastores.tcpServiceDataStore.delete(service.id).futureValue
        ruleServer.stop()
        fallbackServer.stop()
      }
    }
    "shutdown" in {
      stopAll()
    }
  }
}
